import React, { useEffect, useState, useRef } from 'react';
import FullCalendar from '@fullcalendar/react';
import dayGridPlugin from '@fullcalendar/daygrid';
import timeGridPlugin from '@fullcalendar/timegrid';
import interactionPlugin from '@fullcalendar/interaction';
import { sessionsApi } from '../api/sessions';
import { eventsApi } from '../api/events';
import { Session, ExamEvent } from '../types';
import { CheckCircle2, XCircle, Clock, RefreshCw, Calendar as CalendarIcon, AlertCircle } from 'lucide-react';

export const CalendarPage: React.FC = () => {
  const [sessions, setSessions] = useState<Session[]>([]);
  const [examEvents, setExamEvents] = useState<ExamEvent[]>([]);
  const [loading, setLoading] = useState(true);
  const [selectedSession, setSelectedSession] = useState<Session | null>(null);
  const [actualMinutesInput, setActualMinutesInput] = useState<number>(60);
  const calendarRef = useRef<any>(null);

  const loadData = async () => {
    try {
      setLoading(true);
      const [sessionsData, eventsData] = await Promise.all([
        sessionsApi.list(),
        eventsApi.list()
      ]);
      setSessions(sessionsData);
      setExamEvents(eventsData);
    } catch (err) {
      console.error('Failed to load timetable:', err);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    loadData();
  }, []);

  const handleEventClick = (info: any) => {
    const isExam = info.event.extendedProps?.isExam;
    if (isExam) return; // Info only for exams

    const sessId = info.event.id;
    const found = sessions.find((s) => s.id === sessId);
    if (found) {
      setSelectedSession(found);
      setActualMinutesInput(found.planned_minutes);
    }
  };

  const handleUpdateStatus = async (status: 'done' | 'missed') => {
    if (!selectedSession) return;
    try {
      await sessionsApi.updateStatus(selectedSession.id, status, actualMinutesInput);
      setSelectedSession(null);
      await loadData();
    } catch (err) {
      console.error('Failed to update session:', err);
    }
  };

  // Convert study sessions & exams to FullCalendar events
  const studyCalendarEvents = sessions.map((s) => {
    let backgroundColor = s.subject_color || '#0284c7';
    let borderColor = s.subject_color || '#0284c7';

    if (s.status === 'done') {
      backgroundColor = '#10b981'; // green success
      borderColor = '#059669';
    } else if (s.status === 'missed') {
      backgroundColor = '#f43f5e'; // red error
      borderColor = '#e11d48';
    } else if (s.type === 'revision') {
      backgroundColor = '#8b5cf6'; // purple revision
      borderColor = '#7c3aed';
    }

    return {
      id: s.id,
      title: `📖 ${s.topic_name} (${s.planned_minutes}m)`,
      start: s.planned_date,
      allDay: true,
      backgroundColor,
      borderColor,
      textColor: '#ffffff',
      extendedProps: { ...s, isExam: false }
    };
  });

  const examCalendarEvents = examEvents.map((e) => {
    const dateStr = typeof e.due_date === 'string' ? e.due_date.split('T')[0] : '';
    return {
      id: `exam-${e.id}`,
      title: `🎯 EXAM: ${e.title}`,
      start: dateStr,
      allDay: true,
      backgroundColor: '#e11d48', // bright rose
      borderColor: '#be123c',
      textColor: '#ffffff',
      extendedProps: { ...e, isExam: true }
    };
  });

  const calendarEvents = [...studyCalendarEvents, ...examCalendarEvents];

  return (
    <div className="space-y-6 max-w-7xl mx-auto">
      <div className="flex items-center justify-between">
        <div>
          <h1 className="text-xl font-black text-slate-900">Study Timetable Calendar</h1>
          <p className="text-xs text-slate-500">Visual timetable generated by deterministic pure scheduler</p>
        </div>
        <button
          onClick={loadData}
          className="px-3.5 py-2 bg-slate-100 hover:bg-slate-200 text-slate-700 rounded-xl text-xs font-bold flex items-center gap-1.5 transition"
        >
          <RefreshCw className={`w-3.5 h-3.5 ${loading ? 'animate-spin' : ''}`} /> Refresh Schedule
        </button>
      </div>

      <div className="bg-white rounded-2xl p-6 border border-slate-200 shadow-xs">
        <FullCalendar
          ref={calendarRef}
          plugins={[dayGridPlugin, timeGridPlugin, interactionPlugin]}
          initialView="dayGridMonth"
          headerToolbar={{
            left: 'prev,next today',
            center: 'title',
            right: 'dayGridMonth,timeGridWeek,timeGridDay'
          }}
          events={calendarEvents}
          eventClick={handleEventClick}
          height="auto"
          aspectRatio={1.8}
        />
      </div>

      {/* Session Details Modal */}
      {selectedSession && (
        <div className="fixed inset-0 bg-slate-900/60 backdrop-blur-xs flex items-center justify-center p-4 z-50">
          <div className="bg-white rounded-2xl max-w-md w-full p-6 shadow-2xl border border-slate-200 space-y-4">
            <div className="flex items-center justify-between border-b border-slate-100 pb-3">
              <span
                className="px-2.5 py-0.5 rounded text-[10px] font-black uppercase text-white"
                style={{ backgroundColor: selectedSession.subject_color || '#0284c7' }}
              >
                {selectedSession.subject_name || 'Subject'}
              </span>
              <button onClick={() => setSelectedSession(null)} className="text-slate-400 hover:text-slate-600 font-bold">
                ✕
              </button>
            </div>

            <div>
              <h3 className="font-extrabold text-slate-900 text-base">{selectedSession.topic_name}</h3>
              <p className="text-xs text-slate-500 mt-1">
                Planned Date: <span className="font-semibold text-slate-700">{selectedSession.planned_date}</span> • Type:{' '}
                <span className="font-bold text-sky-600 uppercase">{selectedSession.type}</span>
              </p>
              <p className="text-xs text-slate-500">
                Planned Duration: <span className="font-semibold text-slate-700">{selectedSession.planned_minutes} minutes</span>
              </p>
            </div>

            {selectedSession.status === 'planned' ? (
              <div className="space-y-3 pt-3 border-t border-slate-100">
                <div>
                  <label className="block text-xs font-semibold text-slate-700 uppercase mb-1">
                    Actual Minutes Studied
                  </label>
                  <input
                    type="number"
                    min="1"
                    value={actualMinutesInput}
                    onChange={(e) => setActualMinutesInput(parseInt(e.target.value) || 0)}
                    className="w-full px-3 py-2 rounded-xl border border-slate-300 text-xs font-bold"
                  />
                </div>

                <div className="flex items-center justify-end gap-2 pt-2">
                  <button
                    onClick={() => handleUpdateStatus('missed')}
                    className="px-3.5 py-2 bg-rose-50 hover:bg-rose-100 text-rose-700 rounded-xl text-xs font-bold flex items-center gap-1 transition"
                  >
                    <XCircle className="w-3.5 h-3.5" /> Mark Missed
                  </button>
                  <button
                    onClick={() => handleUpdateStatus('done')}
                    className="px-4 py-2 bg-emerald-600 hover:bg-emerald-700 text-white rounded-xl text-xs font-bold shadow-xs flex items-center gap-1 transition"
                  >
                    <CheckCircle2 className="w-3.5 h-3.5" /> Mark Complete
                  </button>
                </div>
              </div>
            ) : (
              <div className="pt-3 border-t border-slate-100 flex items-center justify-between text-xs">
                <span className="font-bold text-slate-600">Session Status:</span>
                <span
                  className={`px-3 py-1 rounded-lg text-xs font-black uppercase ${
                    selectedSession.status === 'done' ? 'bg-emerald-100 text-emerald-800' : 'bg-rose-100 text-rose-800'
                  }`}
                >
                  {selectedSession.status} ({selectedSession.actual_minutes}m)
                </span>
              </div>
            )}
          </div>
        </div>
      )}
    </div>
  );
};
